/** النبرة واللغة: تعليمات تنفيذية تُضاف إلى النهاية */
const toneLine = (tone: string) => `- نبرة الناتج: ${tone}.`;
const langLine = (lang: string) =>
  lang === "ثنائي"
    ? "- اكتب الناتج بالعربية مع إبقاء المصطلحات التقنية المشهورة بالإنجليزية بين قوسين عند الحاجة."
    : lang === "إنجليزي"
      ? "- اكتب الناتج كاملاً بالإنجليزية، مع سلامة الاتجاه والترقيم."
      : "- اكتب الناتج بالعربية الفصحى المبسطة.";

/** بناء رسالة النظام كاملة حسب الفئة واللغة والنبرة والتفصيل */
export function systemPrompt(p: EnhanceInput): string {
  const domain = DOMAINS[p.category?.trim?.() ?? ""] ?? `# مجال الخبرة: عام
- إن كانت الفئة غير محددة، استنتج المجال من نص المستخدم وضَع البرومبت قابلاً للتطبيق في أي مجال مشابه.`;
  return [
    CORE,
    domain,
    `# إعدادات المستخدم المطلوب احترامها
- لغة الناتج: ${p.lang}.\n- نبرة الخطاب: ${p.tone}.\n- درجة التفصيل: ${p.detail}.`,
    DETAIL[p.detail] ?? DETAIL["متوازن"],
    langLine(p.lang),
    toneLine(p.tone),
    `# المعيار النهائي قبل الإخراج
تأكد أن البرومبت: (1) يفهمه أي منفّذ دون سؤال، (2) نتيجته قابلة للقياس، (3) يحترم متغيرات المستخدم بين قوسين، (4) يخلو تماماً من أي ذكر للتقنيات أو النماذج أو المزودين.`,
  ].join("\n\n");
}

